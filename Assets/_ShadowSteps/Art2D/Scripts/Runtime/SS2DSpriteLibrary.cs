    /// <summary>Captured frames of one character for one facing: idle frames and walk-cycle frames, all the same scale.</summary>
    [System.Serializable]
    public sealed class SS2DDirectionFrames
    {
        public Sprite[] idle;
        public Sprite[] walk;
    }

    /// <summary>Four facings (N, E, S, W in <see cref="Direction"/> order) of one character.</summary>
    [System.Serializable]
    public sealed class SS2DCharacterSet
    {
        public string sourcePrefab;
        public SS2DDirectionFrames[] facings = new SS2DDirectionFrames[4];
        public float walkFrameRate = 10f;
        public float idleFrameRate = 2f;

        public Sprite Frame(Direction d, bool walking, int index)
        {
            var f = facings != null && facings.Length == 4 ? facings[(int)d] : null;
            var arr = f == null ? null : walking ? f.walk : f.idle;
            if ((arr == null || arr.Length == 0) && f != null) arr = f.idle;
            if (arr == null || arr.Length == 0) return null;
            return arr[((index % arr.Length) + arr.Length) % arr.Length];
        }
        public int FrameCount(Direction d, bool walking)
        {
            var f = facings != null && facings.Length == 4 ? facings[(int)d] : null;
            var arr = f == null ? null : walking ? f.walk : f.idle;
            return arr != null ? arr.Length : 0;
        }
        public bool IsComplete { get { if (facings == null || facings.Length != 4) return false; foreach (var f in facings) if (f == null || f.idle == null || f.idle.Length == 0 || f.idle[0] == null) return false; return true; } }
    }

